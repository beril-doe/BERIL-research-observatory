"""What ``POST /api/context/ingest_files`` will accept.

Three layers, all checked before the route touches the database or the
context store, so a rejected submission leaves nothing behind:

1. **Shape** — only the files the ``/submit`` mirror stages may be added
   (``ALLOWED_FILES``), and the archive is bounded before and during
   extraction: the upload itself, each member, and the expanded total, read
   from the zip's own directory before anything is written, and the entry
   count is bounded from its end record before the directory is even parsed.
   Only the members the manifest names are extracted.
2. **Approval** — the submission carries the project's ``beril.yaml`` with
   ``status: complete`` and an ``approval`` block whose ``by`` is the caller,
   and the ``REPORT.md`` / ``REVIEW.md`` it carries hash to the approval's
   ``report_hash`` / ``review_hash``. ``project_id`` must name the project
   being ingested into.
3. **Authority** — ``force`` (re-ingest regardless of what landed) is an
   admin repair tool.

This is a consistency check, not proof of review: a client can still forge a
self-consistent ``beril.yaml``. What it does guarantee is that every ingest is
tied to a named approver who is the caller, and that the indexed REPORT and
REVIEW are byte-for-byte the ones that approver signed off on.
"""

from __future__ import annotations

import hashlib
import io
import re
import zipfile
from pathlib import Path

import yaml
from fastapi import HTTPException, UploadFile, status

# Mirrors ``observatory_context.selection.PROJECT_CURATED_NAMES`` (a test pins
# the two together) plus the files ``stage_project`` generates.
ALLOWED_FILES = frozenset(
    {
        "README.md",
        "RESEARCH_PLAN.md",
        "REPORT.md",
        "REVIEW.md",
        "references.md",
        "FINDINGS.md",
        "EXECUTIVE_SUMMARY.md",
        "FAILURE_ANALYSIS.md",
        "DESIGN_NOTES.md",
        "CORRECTIONS.md",
        "beril.yaml",
        # Generated by the mirror's staging step.
        "PROJECT_METADATA.md",
        "CLAIMS_CONTEXT.md",
    }
)
# memories/<name>.md, one level — what ``select_project_memories`` stages.
_MEMORY = re.compile(r"memories/[^/]+\.md")
# REFUTATION_<n>.md, n >= 1 — what ``select_project_refutations`` stages.
_REFUTATION = re.compile(r"REFUTATION_[1-9][0-9]*\.md")

# The files the approval check reads. They must be manifest entries, so a
# submission always carries the approval it is checked against.
APPROVAL_FILES = ("beril.yaml", "REPORT.md", "REVIEW.md")

_HASH_PREFIX = "sha256:"


def disallowed(paths: list[str]) -> list[str]:
    """Paths the mirror would never stage, in manifest order."""
    return [
        p
        for p in paths
        if p not in ALLOWED_FILES
        and not _MEMORY.fullmatch(p)
        and not _REFUTATION.fullmatch(p)
    ]


async def read_capped(upload: UploadFile, limit: int, *, what: str) -> bytes:
    """Read an upload, refusing it once it passes ``limit`` bytes.

    Reads one byte past the limit rather than trusting a declared size, so an
    oversized body is refused without being held in memory whole.
    """
    data = await upload.read(limit + 1)
    if len(data) > limit:
        raise HTTPException(
            status_code=status.HTTP_413_CONTENT_TOO_LARGE,
            detail=f"The {what} is too large (limit {limit} bytes).",
        )
    return data


def archive_entry_count(archive_bytes: bytes) -> int | None:
    """How many entries the archive's central directory declares, or ``None``
    when there is no end-of-central-directory record (not a zip).

    Read from the end record alone — including its zip64 form — without
    parsing the directory. ``zipfile.ZipFile`` materializes every entry as
    soon as it is opened, so this is the only point at which an entry flood
    can be refused before it costs memory and CPU. ``_EndRecData`` is the
    stdlib's own end-record reader (private, but unchanged across releases).
    """
    record = zipfile._EndRecData(io.BytesIO(archive_bytes))
    return None if record is None else record[zipfile._ECD_ENTRIES_TOTAL]


def extract_members(
    archive_bytes: bytes,
    dest: Path,
    members: list[str],
    *,
    max_file_bytes: int,
    max_total_bytes: int,
    max_entries: int,
) -> None:
    """Extract exactly ``members`` from the archive into ``dest``.

    The archive's total entry count is bounded first, from its end record,
    before the directory is parsed — the manifest selects only a few members,
    but opening the archive would materialize every entry, listed or not.
    Then every bound is checked from the central directory before anything is
    written — the declared size of each member and their total — so a zip bomb
    is refused without being inflated. Members the manifest does not name are
    never extracted, whatever the archive carries. Symlinks and entries that
    would land outside ``dest`` are refused; a hostile archive extracts
    nothing.
    """
    entries_total = archive_entry_count(archive_bytes)
    if entries_total is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The uploaded archive could not be read as a zip file.",
        )
    if entries_total > max_entries:
        raise HTTPException(
            status_code=status.HTTP_413_CONTENT_TOO_LARGE,
            detail=(
                f"The archive has {entries_total} entries (limit {max_entries})."
            ),
        )
    try:
        with zipfile.ZipFile(io.BytesIO(archive_bytes)) as zf:
            entries = {info.filename: info for info in zf.infolist()}
            missing = [m for m in members if m not in entries or entries[m].is_dir()]
            if missing:
                raise HTTPException(
                    status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
                    detail=f"Manifest files missing from the archive: {', '.join(missing)}",
                )
            total = 0
            for name in members:
                info = entries[name]
                # Upper 16 bits of external_attr are the Unix mode; 0xA000 is
                # S_IFLNK.
                if (info.external_attr >> 16) & 0xF000 == 0xA000:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Archive contains a symlink: {name!r}",
                    )
                if not (dest / name).resolve().is_relative_to(dest):
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=f"Archive entry escapes the archive root: {name!r}",
                    )
                if info.file_size > max_file_bytes:
                    raise HTTPException(
                        status_code=status.HTTP_413_CONTENT_TOO_LARGE,
                        detail=(
                            f"{name} is too large: {info.file_size} bytes "
                            f"(limit {max_file_bytes})."
                        ),
                    )
                total += info.file_size
            if total > max_total_bytes:
                raise HTTPException(
                    status_code=status.HTTP_413_CONTENT_TOO_LARGE,
                    detail=(
                        f"The archive expands to {total} bytes "
                        f"(limit {max_total_bytes})."
                    ),
                )
            for name in members:
                zf.extract(entries[name], dest)
    except (zipfile.BadZipFile, OSError) as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The uploaded archive could not be read as a zip file.",
        ) from exc


def check_approval(root: Path, *, caller_orcid: str, project_slug: str, slugify) -> None:
    """Refuse a submission that is not an approved project of the caller's.

    ``root`` holds the extracted members; the approval files are guaranteed to
    be among them (the route requires them in the manifest).
    """

    def reject(detail: str, code: int = status.HTTP_422_UNPROCESSABLE_CONTENT):
        raise HTTPException(status_code=code, detail=detail)

    try:
        manifest = yaml.safe_load((root / "beril.yaml").read_text(encoding="utf-8"))
    except (yaml.YAMLError, UnicodeDecodeError):
        reject("beril.yaml could not be parsed.")
    if not isinstance(manifest, dict):
        reject("beril.yaml is not a mapping.")

    project_id = manifest.get("project_id")
    if not isinstance(project_id, str) or slugify(project_id) != project_slug:
        reject(
            f"beril.yaml names project {project_id!r}, not the project being "
            "ingested into."
        )
    if manifest.get("status") != "complete":
        reject(
            f"The project is not approved (status: {manifest.get('status')!r}); "
            "only a completed project can be ingested. Run /submit to approve it."
        )
    approval = manifest.get("approval")
    if not isinstance(approval, dict):
        reject("beril.yaml has no approval block.")
    if approval.get("by") != caller_orcid:
        # Who approved it is the one fact the caller cannot satisfy by
        # editing files they control — it must be themselves.
        reject(
            "The project was approved by someone else; only its approver can "
            "ingest it.",
            status.HTTP_403_FORBIDDEN,
        )
    for name, key in (("REPORT.md", "report_hash"), ("REVIEW.md", "review_hash")):
        stored = approval.get(key)
        if not isinstance(stored, str) or not stored.startswith(_HASH_PREFIX):
            reject(f"approval.{key} is missing or not a sha256 hash.")
        actual = hashlib.sha256((root / name).read_bytes()).hexdigest()
        if stored.removeprefix(_HASH_PREFIX) != actual:
            reject(
                f"{name} does not match approval.{key}; it changed after the "
                "project was approved."
            )
